/** `primarySoft` -> `primary-soft` (the Tailwind color name). */
export function toKebabCase(name: string): string {
  return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

/**
 * The Tailwind v4 `@theme` block of the dashboard, written from the palette above. The file
 * `tokens.css` is this text (`yarn generate:design`); a test fails when the two differ, so the
 * web colors can never drift from the mobile ones.
 *
 * `--color-*: initial` removes Tailwind's default palette: only Medikart colors exist as classes
 * (`bg-primary`, `text-text-secondary`...), so a stray `bg-blue-500` cannot compile.
 */
export function renderTokensCss(
  palette: Readonly<Record<string, string>>,
  fontName: string,
): string {
  const lines = Object.entries(palette).map(
    ([name, value]) => `  --color-${toKebabCase(name)}: ${value};`,
  );
  return [
    '/* GENERATED by `yarn generate:design` in packages/shared from src/design/colors.ts. Do not edit. */',
    '@theme {',
    '  --color-*: initial;',
    ...lines,
    `  --font-sans: '${fontName}', system-ui, sans-serif;`,
    '}',
    '',
  ].join('\n');
}
